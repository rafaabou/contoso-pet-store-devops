RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; PURPLE='\033[0;35m'; CYAN='\033[0;36m'; NC='\033[0m'
BOLD='\033[1m'

check_tool() { command -v "$1" >/dev/null 2>&1; }

get_version() {
    local tool="$1"
    case "$tool" in
        kubectl)     kubectl version --client -o json 2>/dev/null | jq -r '.clientVersion.gitVersion' 2>/dev/null || kubectl version --client --short 2>/dev/null | head -1 || echo "N/A" ;;
        helm)        helm version --short 2>/dev/null || echo "N/A" ;;
        kubectx)     echo "git latest" ;;
        kubens)      echo "git latest" ;;
        k9s)         k9s version 2>/dev/null | grep -i version | head -1 | cut -d' ' -f2 || echo "N/A" ;;
        popeye)      popeye version 2>/dev/null | head -1 | grep -oP 'v\d+\.\d+\.\d+' || echo "installed" ;;
        stern)       stern --version 2>/dev/null | head -1 || echo "N/A" ;;
        kube-linter) kube-linter version 2>/dev/null | head -1 | grep -oP '\d+\.\d+\.\d+' || echo "installed" ;;
        checkov)     checkov --version 2>/dev/null || echo "N/A" ;;
        *) echo "N/A" ;;
    esac
}

