class AllProvidersFailed(Exception):
    def __init__(self, attempted: Dict[str, str]):
        super().__init__("all AI providers failed (see .attempted)")
        self.attempted = attempted


def text_providers() -> List[str]:
    return _ordered_providers("text")


def image_providers() -> List[str]:
    return _ordered_providers("image")


def status() -> Dict[str, List[str]]:
    """Armed providers per capability, in failover order (used by /health)."""
    return {"text": text_providers(), "image": image_providers()}


def generate_text(prompt: str) -> Tuple[str, str]:
    """Try each armed text provider in order; return (text, provider)."""
    attempted: Dict[str, str] = {}
    for provider in text_providers():
        try:
            result = _text_call(provider, _model(provider, "text"), prompt)
            print(f"text generated by provider '{provider}'")
            return result, provider
        except Exception as e:
            attempted[provider] = str(e)
            print(f"text provider '{provider}' failed: {e}")
    if not attempted:
        raise AllProvidersFailed({"config": "no provider armed - set an API key (GEMINI_API_KEY, NVIDIA_API_KEY, CLOUDFLARE_API_TOKEN, XKIRO_API_KEY)"})
    raise AllProvidersFailed(attempted)


def generate_image(prompt: str) -> Tuple[str, str]:
    """Try each armed image provider in order; return (image_data_uri_or_url, provider)."""
    if os.environ.get("AI_IMAGE_PARALLEL", "false").lower() in ("1", "true", "yes"):
        return generate_image_parallel(prompt)
    attempted: Dict[str, str] = {}
    for provider in image_providers():
        try:
            result = _image_call(provider, _model(provider, "image"), prompt)
            print(f"image generated by provider '{provider}'")
            return result, provider
        except Exception as e:
            attempted[provider] = str(e)
            print(f"image provider '{provider}' failed: {e}")
    if not attempted:
        raise AllProvidersFailed({"config": "no provider armed - set an API key (GEMINI_API_KEY, NVIDIA_API_KEY, CLOUDFLARE_API_TOKEN, XKIRO_API_KEY)"})
    raise AllProvidersFailed(attempted)


def generate_image_parallel(prompt: str) -> Tuple[str, str]:
    """Fire all armed image providers concurrently; first success wins.

    Opt-in via AI_IMAGE_PARALLEL=true (default off). Latency drops to the
    fastest leg instead of the sum, but EVERY call consumes quota on ALL
    armed providers at once - with ~170/day Cloudflare and "limited" xKiro
    free tiers, this mode drains budgets several times faster.
    """
    armed = image_providers()
    if not armed:
        raise AllProvidersFailed({"config": "no provider armed - set an API key (GEMINI_API_KEY, NVIDIA_API_KEY, CLOUDFLARE_API_TOKEN, XKIRO_API_KEY)"})
    attempted: Dict[str, str] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(armed)) as pool:
        futures = {
            pool.submit(_image_call, provider, _model(provider, "image"), prompt): provider
            for provider in armed
        }
        for future in concurrent.futures.as_completed(futures):
            provider = futures[future]
            try:
                result = future.result()
                print(f"image generated by provider '{provider}' (parallel)")
                return result, provider
            except Exception as e:
                attempted[provider] = str(e)
                print(f"image provider '{provider}' failed: {e}")
    raise AllProvidersFailed(attempted)


def _ordered_providers(capability: str) -> List[str]:
    env_name = "AI_TEXT_PROVIDERS" if capability == "text" else "AI_IMAGE_PROVIDERS"
    default = DEFAULT_TEXT_PROVIDERS if capability == "text" else DEFAULT_IMAGE_PROVIDERS
    order = [p.strip() for p in os.environ.get(env_name, default).split(",") if p.strip()]
    return [p for p in order if p in PROVIDERS and _is_armed(p)]


def _is_armed(provider: str) -> bool:
    """Armed = API key env var set, plus any extra required env vars (e.g. Account ID)."""
    conf = PROVIDERS[provider]
    if not os.environ.get(conf["key_env"]):
        return False
    return all(os.environ.get(e) for e in conf.get("extra_env", []))


def _model(provider: str, capability: str) -> str:
    conf = PROVIDERS[provider]
    suffix = "image" if capability == "image" else "text"
    return os.environ.get(conf[f"{suffix}_model_env"]) or conf[f"{suffix}_model_default"]


def _text_call(provider: str, model: str, prompt: str) -> str:
    conf = PROVIDERS[provider]
    if conf["sdk"] == "genai":
        response = get_gemini().models.generate_content(model=model, contents=prompt)
        return response.text.strip()
    client = get_openai(os.environ[conf["key_env"]], conf["base_url"])
    response = client.chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": prompt}],
    )
    return response.choices[0].message.content.strip()


def _image_call(provider: str, model: str, prompt: str) -> str:
    conf = PROVIDERS[provider]
    if provider == "gemini":
        return _gemini_image(get_gemini(), model, prompt)
    if provider == "nvidia":
        return _nvidia_image(os.environ[conf["key_env"]], model, prompt)
    if provider == "cloudflare":
        return _cloudflare_image(
            os.environ[conf["key_env"]], os.environ[conf["extra_env"][0]], model, prompt
        )
    if provider == "xkiro":
        return _xkiro_image(os.environ[conf["key_env"]], model, prompt)
    client = get_openai(os.environ[conf["key_env"]], conf["base_url"])
    response = client.images.generate(model=model, prompt=prompt)
    item = response.data[0]
    if getattr(item, "b64_json", None):
        return _data_uri(item.b64_json)
    if getattr(item, "url", None):
        return item.url
    raise Exception("image response contained no b64_json or url")


def _gemini_image(client, model: str, prompt: str) -> str:
    from google.genai import types

    response = client.models.generate_content(
        model=model,
        contents=prompt,
        config=types.GenerateContentConfig(response_modalities=["IMAGE", "TEXT"]),
    )
    for part in response.candidates[0].content.parts:
        if part.inline_data:
            data = part.inline_data.data
            if isinstance(data, bytes):
                data = base64.b64encode(data).decode("ascii")
            mime = part.inline_data.mime_type or "image/png"
            return f"data:{mime};base64,{data}"
    raise Exception("no image returned by the model")


def _nvidia_image(api_key: str, model: str, prompt: str) -> str:
    # NVIDIA's hosted free tier exposes FLUX etc. at ai.api.nvidia.com/v1/genai/{model}
    # (the "Infer" endpoint), returning {"artifacts":[{"base64": <jpeg>}]}.
    response = httpx.post(
        f"https://ai.api.nvidia.com/v1/genai/{model}",
        headers={
            "Authorization": f"Bearer {api_key}",
            "Accept": "application/json",
        },
        json={"prompt": prompt, "width": 1024, "height": 1024, "steps": 4, "seed": 0},
        timeout=600.0,
    )
    response.raise_for_status()
    artifacts = response.json().get("artifacts", [])
    if not artifacts:
        raise Exception("NVIDIA returned no image artifacts")
    image_b64 = artifacts[0].get("base64", "")
    if not image_b64:
        raise Exception("NVIDIA image artifact contained no base64 payload")
    return f"data:image/jpeg;base64,{image_b64}"


def _cloudflare_image(api_token: str, account_id: str, model: str, prompt: str) -> str:
    # Cloudflare Workers AI REST API: POST .../ai/run/{model} with {"prompt": ...}.
    # Response: {"result": {"image": "<base64>"}, "success": true, ...}.
    # Free plan: 10,000 Neurons/day (~170 FLUX images/day).
    response = httpx.post(
        f"https://api.cloudflare.com/client/v4/accounts/{account_id}/ai/run/{model}",
        headers={"Authorization": f"Bearer {api_token}"},
        json={"prompt": prompt, "steps": 4},
        timeout=600.0,
    )
    response.raise_for_status()
    data = response.json()
    if not data.get("success", False):
        raise Exception(f"Cloudflare error: {data.get('errors')}")
    image_b64 = (data.get("result") or {}).get("image", "")
    if not image_b64:
        raise Exception("Cloudflare returned no image")
    return f"data:image/png;base64,{image_b64}"


def _xkiro_image(api_key: str, model: str, prompt: str) -> str:
    # xKiro image API is ASYNCHRONOUS: POST /v1/images/generations returns 202 with
    # {"id": job_id}; poll GET /v1/images/generations/{id} until "succeeded", then
    # data[0].url is a CDN link which is fetched and wrapped as a data URI
    # (matches our contract). Free plan: a few free images per rolling 24h
    # ("limited"); failed jobs are not billed. Poll gently with backoff (docs ask
    # for seconds between polls, not tight loops) and give up after 600s.
    headers = {"Authorization": f"Bearer {api_key}"}
    created = httpx.post(
        "https://api.xkiro.com/v1/images/generations",
        headers=headers,
        json={"model": model, "prompt": prompt, "n": 1, "size": "1024x1024"},
        timeout=60.0,
    )
    created.raise_for_status()
    job_id = created.json().get("id", "")
    if not job_id:
        raise Exception("xKiro returned no job id")
    deadline = time.monotonic() + 600.0
    wait = 2.0
    while time.monotonic() < deadline:
        time.sleep(wait)
        wait = min(wait * 1.5, 10.0)
        job = httpx.get(
            f"https://api.xkiro.com/v1/images/generations/{job_id}",
            headers=headers,
            timeout=60.0,
        )
        job.raise_for_status()
        body = job.json()
        status = body.get("status", "")
        if status == "succeeded":
            data = body.get("data") or []
            url = data[0].get("url", "") if data else ""
            if not url:
                raise Exception("xKiro job succeeded with no image url")
            img = httpx.get(url, timeout=300.0)
            img.raise_for_status()
            mime = img.headers.get("content-type", "image/png").split(";")[0].strip()
            image_b64 = base64.b64encode(img.content).decode("ascii")
            return f"data:{mime};base64,{image_b64}"
        if status in ("failed", "blocked"):
            error = body.get("error") or status
            message = error.get("message", status) if isinstance(error, dict) else str(error)
            raise Exception(f"xKiro job {status}: {message}")
    raise Exception("xKiro image generation timed out")


def _data_uri(b64_or_uri: str) -> str:
    if b64_or_uri.startswith("data:"):
        return b64_or_uri
    if b64_or_uri.startswith("http"):
        return b64_or_uri
    return f"data:image/png;base64,{b64_or_uri}"